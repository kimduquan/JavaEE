package epf.persistence.remote;

import java.rmi.RemoteException;
import java.sql.Connection;
import java.sql.SQLClientInfoException;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.Savepoint;
import java.util.Map;
import java.util.Properties;
import java.util.concurrent.Executor;

public interface RemoteConnection extends Connection, RemoteWrapper {
	RemoteStatement _createStatement() throws RemoteException, SQLException;
	RemotePreparedStatement _prepareStatement(final String sql) throws RemoteException, SQLException;
	RemoteCallableStatement _prepareCall(final String sql) throws RemoteException, SQLException;
	String _nativeSQL(final String sql) throws RemoteException, SQLException;
	void _setAutoCommit(boolean autoCommit) throws RemoteException, SQLException;
	boolean _getAutoCommit() throws RemoteException, SQLException;
	void _commit() throws RemoteException, SQLException;
	void _rollback() throws RemoteException, SQLException;
	void _close() throws RemoteException, SQLException;
	boolean _isClosed() throws RemoteException, SQLException;
	RemoteDatabaseMetaData _getMetaData() throws RemoteException, SQLException;
	void _setReadOnly(boolean readOnly) throws RemoteException, SQLException;
	boolean _isReadOnly() throws RemoteException, SQLException;
	void _setCatalog(String catalog) throws RemoteException, SQLException;
	String _getCatalog() throws RemoteException, SQLException;
	void _setTransactionIsolation(int level) throws RemoteException, SQLException;
	int _getTransactionIsolation() throws RemoteException, SQLException;
	SQLWarning _getWarnings() throws RemoteException, SQLException;
	void _clearWarnings() throws RemoteException, SQLException;
	RemoteStatement _createStatement(int resultSetType, int resultSetConcurrency) throws RemoteException, SQLException;
	RemotePreparedStatement _prepareStatement(String sql, int resultSetType, int resultSetConcurrency) throws RemoteException, SQLException;
	RemoteCallableStatement _prepareCall(String sql, int resultSetType, int resultSetConcurrency) throws RemoteException, SQLException;
	Map<String,Class<?>> _getTypeMap() throws RemoteException, SQLException;
	void _setTypeMap(Map<String,Class<?>> map) throws RemoteException, SQLException;
	void _setHoldability(int holdability) throws RemoteException, SQLException;
	int _getHoldability() throws RemoteException, SQLException;
	RemoteSavepoint _setSavepoint() throws RemoteException, SQLException;
	RemoteSavepoint _setSavepoint(String name) throws RemoteException, SQLException;
	void _rollback(Savepoint savepoint) throws RemoteException, SQLException;
	void _releaseSavepoint(Savepoint savepoint) throws RemoteException, SQLException;
	RemoteStatement _createStatement(int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws RemoteException, SQLException;
	RemotePreparedStatement _prepareStatement(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws RemoteException, SQLException;
	RemoteCallableStatement _prepareCall(String sql, int resultSetType, int resultSetConcurrency, int resultSetHoldability) throws RemoteException, SQLException;
	RemotePreparedStatement _prepareStatement(String sql, int autoGeneratedKeys) throws RemoteException, SQLException;
	RemotePreparedStatement _prepareStatement(String sql, int columnIndexes[]) throws RemoteException, SQLException;
	RemotePreparedStatement _prepareStatement(String sql, String columnNames[]) throws RemoteException, SQLException;
	RemoteClob _createClob() throws RemoteException, SQLException;
	RemoteBlob _createBlob() throws RemoteException, SQLException;
	RemoteNClob _createNClob() throws RemoteException, SQLException;
	RemoteSQLXML _createSQLXML() throws RemoteException, SQLException;
    boolean _isValid(int timeout) throws RemoteException, SQLException;
    void _setClientInfo(String name, String value) throws RemoteException, SQLClientInfoException;
    void _setClientInfo(Properties properties) throws RemoteException, SQLClientInfoException;
    String _getClientInfo(String name) throws RemoteException, SQLException;
    Properties _getClientInfo() throws RemoteException, SQLException;
    RemoteArray _createArrayOf(String typeName, Object[] elements) throws RemoteException, SQLException;
    RemoteStruct _createStruct(String typeName, Object[] attributes) throws RemoteException, SQLException;
    void _setSchema(String schema) throws RemoteException, SQLException;
    String _getSchema() throws RemoteException, SQLException;
    void _abort(Executor executor) throws RemoteException, SQLException;
    void _setNetworkTimeout(Executor executor, int milliseconds) throws RemoteException, SQLException;
    int _getNetworkTimeout() throws RemoteException, SQLException;
}
